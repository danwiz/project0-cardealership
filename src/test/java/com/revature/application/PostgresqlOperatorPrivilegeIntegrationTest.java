package com.revature.application;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.sql.Connection;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.UUID;

import org.junit.jupiter.api.Assumptions;
import org.junit.jupiter.api.Tag;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.function.Executable;

import com.revature.cardealer.AccountRole;
import com.revature.cardealer.User;
import com.revature.repository.jdbc.JdbcDatabase;
import com.revature.repository.jdbc.JdbcUserAccountRepository;
import com.revature.service.UserLoginService;
import com.revature.support.TestAccounts;

/**
 * Real PostgreSQL dialect and SQL grant checks. Enabled only for an isolated
 * CI PostgreSQL service by explicit environment configuration.
 *
 * This validates the separate account operator's reader/writer roles,
 * NOT the broader dealership runtime's eventual least-privilege policy.
 */
@Tag("POSTGRESQL")
@Tag("SECURITY")
class PostgresqlOperatorPrivilegeIntegrationTest {

    @Test
    void distinctDatabaseRolesPermitOperatorChangesButDenyReaderWrites() throws Exception {
        String baseUrl = System.getenv("DEALERSHIP_PG_TEST_URL");
        String ownerName = System.getenv("DEALERSHIP_PG_TEST_USER");
        String ownerPassword = System.getenv("DEALERSHIP_PG_TEST_PASSWORD");
        Assumptions.assumeTrue("true".equalsIgnoreCase(System.getenv("CI"))
                        && "jdbc:postgresql://localhost:5432/dealership_ci".equals(baseUrl)
                        && "dealership_ci_owner".equals(ownerName)
                        && "ci-only-postgres-fixture".equals(ownerPassword),
                "Operator grant integration only runs against the exact disposable CI fixture");

        // All identifiers are generated by this test, not constructed from user input.
        String suffix = UUID.randomUUID().toString().replace("-", "");
        String schema = "pgt_" + suffix;
        String readerRole = "read_" + suffix;
        String operatorRole = "write_" + suffix;
        String url = baseUrl + (baseUrl.contains("?") ? "&" : "?") + "currentSchema=" + schema;

        JdbcDatabase serverOwner = new JdbcDatabase(baseUrl, ownerName, ownerPassword);
        try (Connection connection = serverOwner.openConnection();
                Statement statement = connection.createStatement()) {
            statement.execute("CREATE SCHEMA " + schema);
            statement.execute("CREATE ROLE " + readerRole
                    + " LOGIN PASSWORD 'isolated-reader-fixture-secret'");
            statement.execute("CREATE ROLE " + operatorRole
                    + " LOGIN PASSWORD 'isolated-operator-fixture-secret'");
        }

        // Applies the existing full version-4 migration against actual PostgreSQL.
        JdbcDatabase migrator = new JdbcDatabase(url, ownerName, ownerPassword);
        migrator.migrate();
        assertEquals(JdbcDatabase.CURRENT_SCHEMA_VERSION, migrator.schemaVersion());

        JdbcUserAccountRepository privilegedFixture = new JdbcUserAccountRepository(migrator);
        TestAccounts.seed(privilegedFixture, AccountRole.ADMINISTRATOR,
                "root_" + suffix, "correct-admin-password");
        TestAccounts.seed(privilegedFixture, AccountRole.EMPLOYEE,
                "existing_" + suffix, "employee-password");

        try (Connection connection = serverOwner.openConnection();
                Statement statement = connection.createStatement()) {
            statement.execute("GRANT USAGE ON SCHEMA " + schema + " TO "
                    + readerRole + ", " + operatorRole);
            statement.execute("GRANT SELECT ON TABLE " + schema + ".schema_history, "
                    + schema + ".accounts TO " + readerRole + ", " + operatorRole);
            statement.execute("GRANT INSERT, UPDATE, DELETE ON TABLE " + schema
                    + ".accounts TO " + operatorRole);
        }

        JdbcDatabase readerDatabase = new JdbcDatabase(url, readerRole,
                "isolated-reader-fixture-secret");
        JdbcDatabase writerDatabase = new JdbcDatabase(url, operatorRole,
                "isolated-operator-fixture-secret");
        JdbcUserAccountRepository reader = new JdbcUserAccountRepository(readerDatabase);
        JdbcUserAccountRepository writer = new JdbcUserAccountRepository(writerDatabase);
        UserLoginService operator = new UserLoginService(reader, writer);
        String rootName = "root_" + suffix;
        String employeeName = "existing_" + suffix;

        assertPermissionDenied(() ->
                reader.save(account("forbidden_" + suffix, AccountRole.ADMINISTRATOR)));
        assertPermissionDenied(() ->
                reader.updateRoleIfCurrent(employeeName,
                        AccountRole.EMPLOYEE, AccountRole.ADMINISTRATOR));
        assertPermissionDenied(() -> reader.removeByUsername(employeeName));

        try (Connection connection = readerDatabase.openConnection();
                Statement statement = connection.createStatement()) {
            assertSqlPermissionDenied(() -> statement.execute(
                    "CREATE TABLE " + schema + ".forbidden_ddl (id INTEGER)"));
            assertSqlPermissionDenied(() -> statement.executeUpdate(
                    "UPDATE " + schema + ".administrator_bootstrap_state "
                    + "SET initial_admin_username = 'unauthorized' WHERE bootstrap_id = 1"));
        }

        User actor = credentials(rootName, "correct-admin-password");
        String newStaff = "staff_" + suffix;
        assertTrue(AccountAdministrationCli.execute(operator, actor,
                AccountAdministrationCli.Action.PROVISION,
                newStaff, null, AccountRole.EMPLOYEE, "employee-password"));
        assertEquals(AccountRole.EMPLOYEE,
                reader.findByUsername(newStaff).orElseThrow(AssertionError::new).getRole());
        assertTrue(AccountAdministrationCli.execute(operator, actor,
                AccountAdministrationCli.Action.CHANGE_ROLE,
                newStaff, AccountRole.EMPLOYEE, AccountRole.ADMINISTRATOR, null));
        assertTrue(AccountAdministrationCli.execute(operator, actor,
                AccountAdministrationCli.Action.DELETE,
                newStaff, null, null, null));
        assertFalse(reader.findByUsername(newStaff).isPresent());
        assertThrows(SecurityException.class, () -> writer.removeByUsername(rootName));
        assertEquals(AccountRole.ADMINISTRATOR,
                reader.findByUsername(rootName).orElseThrow(AssertionError::new).getRole());
    }

    private static void assertPermissionDenied(Executable attempt) {
        IllegalStateException failure = assertThrows(IllegalStateException.class, attempt);
        Throwable cause = failure;
        while (cause != null && !(cause instanceof SQLException)) cause = cause.getCause();
        assertTrue(cause instanceof SQLException, "expected JDBC permission denial");
        assertEquals("42501", ((SQLException) cause).getSQLState());
    }

    private static void assertSqlPermissionDenied(Executable attempt) {
        SQLException failure = assertThrows(SQLException.class, attempt);
        assertEquals("42501", failure.getSQLState());
    }

    private static User credentials(String username, String password) {
        User account = new User();
        account.setUsername(username);
        account.setPassword(password);
        return account;
    }

    private static User account(String username, AccountRole role) {
        User account = new User();
        account.setUsername(username);
        account.setPassword("encoded-test-credential");
        account.setRole(role);
        return account;
    }
}
